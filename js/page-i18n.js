let pageLang = (function(){
  try { var q = new URLSearchParams(location.search).get('lang'); if (q==='hi'||q==='en') return q; } catch(e){}
  try { return localStorage.getItem('vkstech_lang') || 'en'; } catch(e){ return 'en'; }
})();
function setLang(lang){
  pageLang = lang;
  try { localStorage.setItem('vkstech_lang', lang); } catch(e){}
  document.documentElement.lang = lang;
  var t = lang === 'hi' ? PAGE_HI : PAGE_EN;
  document.querySelectorAll('[data-i]').forEach(function(el){ var k=el.getAttribute('data-i'); if(t[k]) el.innerHTML=t[k]; });
  document.querySelectorAll('.lpill').forEach(function(p){
    p.classList.toggle('active', p.textContent.trim() === (lang==='hi'?'हिं':'EN'));
  });
}
document.addEventListener('DOMContentLoaded', function(){ if(pageLang==='hi') setLang('hi'); });
